"""
Regression fixtures for the shared run machinery: run IDs, identity
hashes, W&B logger kwargs / artifact metadata, and the pull --check
report.

Target: the first pilot's run machinery (01_train.py / 03_pull.py / the
artifact helpers) after the shared-code move.
Run with: pytest experiments/03_multistate_gdn2/01_synthetic_pilot/test_run_machinery_fixtures.py -v

The fixture files were generated by
``fixtures/make_run_machinery_fixture.py`` on the reference checkout
(master before the move). A change to any of these outputs must be
reviewed deliberately; this test fails rather than silently accepting it.
"""

import importlib.util
import json
import sys
from functools import partial
from pathlib import Path

from omegaconf import OmegaConf

_PILOT = Path(__file__).resolve().parent
_SRC = _PILOT.parents[2] / "src"
for _p in (_PILOT, _SRC):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

# The fixture generator (importing it is safe: nothing runs on import).
_HERE = _PILOT / "fixtures"
_spec = importlib.util.spec_from_file_location(
    "run_mach_fixture", _HERE / "make_run_machinery_fixture.py"
)
_gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_gen)


def make_train():
    spec = importlib.util.spec_from_file_location(
        "pilot_train_fixture", _PILOT / "01_train.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _load(name):
    return json.loads((_HERE / name).read_text())


class TestRunIdentity:
    """Run IDs and identity hashes match the reference fixtures."""

    def test_run_ids_and_hashes(self):
        train = make_train()
        expect = _load("run_identity.json")
        for label, overrides in _gen.REPRESENTATIVES.items():
            cfg = _gen.compose(overrides)
            run_id = train.make_run_id(cfg, 0.003)
            cfg_dict = {k: v for k, v in cfg.items() if k != "hydra"}
            container = OmegaConf.to_container(OmegaConf.create(cfg_dict), resolve=True)
            hash_ = train.config_hash(container, train.HASH_EXCLUDE)
            assert run_id == expect[label]["run_id"], label
            assert hash_ == expect[label]["config_hash"], label


class TestWandbSample:
    """W&B logger kwargs and artifact metadata match the reference."""

    def test_sample_matches(self):
        train = make_train()
        expect = _load("wandb_sample.json")
        cfg = _gen.compose(
            {
                "task": "overwrite",
                "model.gate_mode": "full",
                "model.layout": "ws",
                "experiment.tier": "tier1_core",
            }
        )
        run_id = train.make_run_id(cfg, 0.003)
        kwargs = train.wandb_logger_kwargs(cfg, run_id)
        kwargs["config"] = None
        assert kwargs == expect["wandb_logger_kwargs"]
        assert run_id == expect["run_id"]
        record = {
            "run_id": run_id,
            "status": "test_done",
            "config_hash": expect_config_hash(train),
            "seed": 0,
            "config": {
                "task": {"name": "overwrite"},
                "experiment": {"tier": "tier1_core"},
            },
            "git": {"commit": "beef", "dirty": False},
            "provenance": {"uv.lock": "deadbeef"},
        }
        assert train.run_record_metadata(record) == expect["artifact_metadata"]


def expect_config_hash(train):
    return _load("run_identity.json")["tier1_core_overwrite_full_ll"]["config_hash"]


class TestPullReport:
    """The pull --check report matches the reference, with and without a
    tier filter."""

    def test_pull_report_matches(self, tmp_path):
        train = make_train()
        all_text = _gen.pull_report(train, None, tmp_path, None)
        assert all_text + "\n" == (_HERE / "pull_report.txt").read_text()

    def test_pull_report_tier_matches(self, tmp_path):
        train = make_train()
        tier_text = _gen.pull_report(train, None, tmp_path, "tier3_frozen")
        assert tier_text + "\n" == (_HERE / "pull_report_tier3.txt").read_text()
